//! MAVLink 2 device layer for the MARV V2 flight controller: the sans-IO core.
//!
//! [`Node`] takes bytes and a time in and gives frames out. It knows nothing about USB, a
//! transport or an executor, and owns no clock, allocation, `static` or critical section: time
//! comes only through `now_us`. The message types come from `marv-dialect`
//! ([`dialect`]); frames are built at the message-struct level only
//! (`MAVLinkV2MessageRaw::serialize_message_data`, `MessageData::deser`, `calculate_crc`).
//!
//! It has framing, the node's identity and HEARTBEAT, presence of the ground station, the stream
//! scheduler with the firmware's [`Telemetry`] hook, the STATUSTEXT queue, the parameter protocol over
//! the firmware's [`ParamStore`], the commands SET_MESSAGE_INTERVAL and REQUEST_MESSAGE (and
//! UNSUPPORTED for the rest), and [`Node::run`], the one async function that drives a node on an
//! `embedded_io_async` reader and writer.
//!
//! ```
//! use mavlink_device::{Config, Node, Outgoing, ParamName, ParamStore, ParamValue, ParamError,
//!     Stream, StreamSlot, Telemetry};
//!
//! struct NoParams;
//! impl ParamStore for NoParams {
//!     fn count(&self) -> u16 { 0 }
//!     fn name(&self, _: u16) -> Option<ParamName> { None }
//!     fn get(&self, _: u16) -> Option<ParamValue> { None }
//!     fn find(&self, _: &ParamName) -> Option<u16> { None }
//!     fn set(&mut self, _: u16, _: ParamValue) -> Result<ParamValue, ParamError> { Err(ParamError::NotFound) }
//! }
//! struct Pressure;
//! impl Telemetry for Pressure {
//!     fn sample(&mut self, id: u32, now_us: u64, out: &mut Outgoing<'_>) -> bool {
//!         let m = mavlink_device::dialect::SCALED_PRESSURE_DATA { time_boot_ms: (now_us / 1000) as u32, ..Default::default() };
//!         id == 29 && out.push(&m).is_ok()
//!     }
//! }
//! let mut slots = [StreamSlot::new(Stream { message_id: 29, default_interval_us: 100_000, min_interval_us: 20_000 })];
//! let mut node = Node::new(Config::new(1, 1), &mut slots);
//! let mut frame = [0u8; 280];
//! let n = node.poll_transmit(0, &NoParams, &mut Pressure, &mut frame).unwrap();
//! assert_eq!(frame[0], 0xFD); // the first frame is the HEARTBEAT
//! assert!(n > 10);
//! assert_eq!(node.next_deadline_us(), 0); // the pressure sample is due now
//! ```
